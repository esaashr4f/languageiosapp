// Regenerates PROGRESS.md from languages.json and the content folders.
// Usage: tsx tools/stats.ts [--date YYYY-MM-DD]   (date stamps languages whose numbers changed)
import fs from "node:fs";
import path from "node:path";
import { args, lessonFiles, parseLesson, readJson, wordCounts, type Syllabus } from "./lib.ts";

const a = args();
const today = a.flag("--date") ?? new Date().toISOString().slice(0, 10);
const languages = readJson<{ languages: { number: number; name: string; iso: string; depth: string; pilot?: number }[] }>("languages.json")!.languages;
const prev = new Map<string, { sig: string; date: string }>();
if (fs.existsSync("PROGRESS.md"))
  for (const line of fs.readFileSync("PROGRESS.md", "utf8").split("\n")) {
    const c = line.split("|").map((x) => x.trim());
    if (c.length >= 10 && /^`[a-z]{3}`$/.test(c[3])) prev.set(c[3].slice(1, -1), { sig: c.slice(5, 9).join("|"), date: c[9] });
  }

const rows: string[] = [];
let totalWords = 0, totalDone = 0, totalUnverified = 0;
for (const l of languages) {
  const dir = path.join("content", l.iso);
  const syllabus = readJson<Syllabus>(path.join(dir, "syllabus.json"));
  const status = readJson<{ lessons: Record<string, { state: string }> }>(path.join(dir, "STATUS.json"));
  let stage = "not started", lessons = "0/0", words = 0, unverified = 0;
  if (fs.existsSync(path.join(dir, "dossier.md"))) stage = "dossier";
  if (syllabus) {
    stage = "syllabus";
    const partOf = new Map(syllabus.lessons.map((s) => [s.id, s.part]));
    const states = syllabus.lessons.map((s) => status?.lessons[s.id]?.state ?? "planned");
    const n = (s: string) => states.filter((x) => x === s).length;
    const written = states.length - n("planned");
    for (const f of lessonFiles(dir)) {
      const p = parseLesson(f);
      words += wordCounts(p.blocks).prose;
      const part = partOf.get(p.front.id ?? "") ?? 0;
      if (part >= 1 && part <= 6) for (const b of p.blocks) if ((b.type === "example" || b.type === "table") && b.fields.confidence === "unverified") unverified++;
    }
    if (written > 0) stage = "draft";
    if (written === states.length && n("drafted") === 0) stage = "verified";
    if (n("done") === states.length) { stage = "done"; totalDone++; }
    lessons = `${n("done") + n("verified")}v+${n("drafted")}d/${states.length}`;
  }
  totalWords += words; totalUnverified += unverified;
  const sig = [stage, lessons, words.toLocaleString("en-GB"), String(unverified)].join("|");
  const old = prev.get(l.iso);
  const date = stage === "not started" ? "" : old && old.sig === sig ? old.date : today;
  rows.push(`| ${l.number} | ${l.name}${l.pilot ? " (pilot)" : ""} | \`${l.iso}\` | ${l.depth} | ${sig.replace(/\|/g, " | ")} | ${date} |`);
}
const head = `# Progress

Generated by \`npm run stats\`. Do not edit by hand.

Lessons column: \`verified+drafted/planned\` (v = verified or done, d = drafted and awaiting verification). Words are prose words (headings, paragraphs, lists and exercises), the measure used for the depth-class ranges; example, table and vocabulary blocks are not counted. Unverified counts examples and tables labelled \`unverified\` in parts 1 to 6.

**Totals:** ${totalDone}/100 guides done, ${totalWords.toLocaleString("en-GB")} words written, ${totalUnverified} open unverified items.

Writing order: pilot (lat, kat, gez, tur, nav, nci), then 72 to 100, then 59 to 71, then 1 to 58.

| # | Language | ISO | Depth | Stage | Lessons | Words | Unverified | Last session |
|---|---|---|---|---|---|---|---|---|
`;
fs.writeFileSync("PROGRESS.md", head + rows.join("\n") + "\n");
console.log(`PROGRESS.md: ${totalDone}/100 done, ${totalWords} words, ${totalUnverified} unverified`);
